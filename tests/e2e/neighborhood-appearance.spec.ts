import { expect } from '@playwright/test';
import { test, capture, resize } from './visual-fixture.ts';
import { showAdvanced } from './settings-helpers.ts';

test('pixel neighborhood settings save, cancel, reset and update every view without changing membership', async ({ visual: { app, page } }) => {
  const field = page.locator('[data-project-field="billing"]');
  const logical = page.locator('[data-project-outline="billing"]');
  const paths = () => field.locator('.neighborhood-paint > path').evaluateAll(paths => paths.map(path => path.getAttribute('d')));
  await expect(field).toHaveAttribute('data-pixel-size', '24');
  await expect(field).toHaveAttribute('data-fade', '96');
  await expect(field).toHaveAttribute('data-scatter', '0');
  await expect(page.getByLabel('Project neighborhoods', { exact: true })).toHaveAttribute('opacity', '.24');
  expect(await logical.evaluate(el => getComputedStyle(el).stroke)).toBe('none');
  const before = await page.evaluate(async () => ({ graph: (await window.craftingTable.workspaceRead()).state, view: await window.craftingTable.viewRead() }));
  const boundary = await logical.getAttribute('d'), original = await paths();
  expect(original.filter(Boolean)).toHaveLength(4);
  const open = async () => { await page.getByRole('button', { name: 'Settings', exact: true }).click(); await page.getByRole('treeitem', { name: 'Map', exact: true }).click(); await showAdvanced(page); };
  await open();
  await page.getByLabel('Pixel size', { exact: true }).fill('48');
  await page.getByLabel('Fade distance', { exact: true }).fill('144');
  await page.getByRole('slider', { name: 'Edge scatter', exact: true }).press('End');
  await page.getByRole('button', { name: 'Discard', exact: true }).click();
  expect(await paths()).toEqual(original);
  await open();
  await expect(page.getByLabel('Pixel size', { exact: true })).toHaveValue('24');
  await page.getByLabel('Pixel size', { exact: true }).fill('7');
  await page.getByRole('button', { name: 'Save settings' }).click();
  expect(await page.getByLabel('Pixel size', { exact: true }).evaluate((el: HTMLInputElement) => el.validity.rangeUnderflow)).toBe(true);
  await page.getByLabel('Pixel size', { exact: true }).fill('48');
  await page.getByLabel('Fade distance', { exact: true }).fill('144');
  await page.getByRole('slider', { name: 'Edge scatter', exact: true }).press('End');
  await resize(app, page, 900, 640);
  await page.getByRole('group', { name: 'Neighborhood appearance', exact: true }).scrollIntoViewIfNeeded();
  await capture(page, 'settings-neighborhood-appearance.png');
  await page.getByRole('button', { name: 'Save settings' }).click();
  await expect(field).toHaveAttribute('data-pixel-size', '48');
  await expect(field).toHaveAttribute('data-fade', '144');
  await expect(field).toHaveAttribute('data-scatter', '100');
  expect(await paths()).not.toEqual(original);
  expect(await logical.getAttribute('d')).toBe(boundary);
  expect((await page.evaluate(() => window.craftingTable.workspaceRead())).state).toEqual(before.graph);
  await resize(app, page, 1280, 800);
  await capture(page, 'map-neighborhood-scatter.png');
  await open(); await page.getByRole('button', { name: 'Reset appearance' }).click(); await page.getByRole('button', { name: 'Save settings' }).click();
  await expect.poll(paths).toEqual(original);
  await page.getByRole('article', { name: 'Plan switcher', exact: true }).click();
  await expect(page.locator('.map-area')).toHaveAttribute('data-focus', 'pr');
  const viewed = (await page.evaluate(() => window.craftingTable.workspaceRead())).state;
  expect(viewed).toEqual(before.graph);
  await page.evaluate(async () => { const s = await window.craftingTable.settingsRead(); await window.craftingTable.settingsWrite({ expectedRevision: s.revision, value: { ...s.value, neighborhoodAppearance: { ...s.value.neighborhoodAppearance, pixelSize: 32, fade: 0, scatter: 0 } } }); });
  await expect(field).toHaveAttribute('data-pixel-size', '32');
  expect(await field.evaluate(el => el.getAnimations({ subtree: true }).length)).toBe(0);
  await expect.poll(async () => (await paths()).filter(Boolean).length).toBe(1);
  await expect(page.locator('.focus-neighborhood-frame')).toHaveCount(0);
  expect(await logical.getAttribute('d')).toBe(boundary);
  await page.getByRole('button', { name: 'Back to project', exact: true }).click();
  expect((await page.evaluate(() => window.craftingTable.workspaceRead())).state).toEqual(viewed);
  expect((await page.evaluate(() => window.craftingTable.viewRead())).camera).toEqual(before.view.camera);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  const animationCount = await page.evaluate(async () => {
    const s = await window.craftingTable.settingsRead();
    await window.craftingTable.settingsWrite({ expectedRevision: s.revision, value: { ...s.value, neighborhoodAppearance: { ...s.value.neighborhoodAppearance, pixelSize: 24, fade: 96, scatter: 0 } } });
    const root = document.querySelector('[data-project-field="billing"]')!;
    let most = 0, start = performance.now();
    while (performance.now() - start < 250) { most = Math.max(most, root.getAnimations({ subtree: true }).length); await new Promise(requestAnimationFrame); }
    return { most, idle: root.getAnimations({ subtree: true }).length };
  });
  expect(animationCount.most).toBeGreaterThan(0); expect(animationCount.idle).toBe(0);
});
