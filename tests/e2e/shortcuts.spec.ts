test('T toggles to-dos; a slot click opens and pins, a second click closes, and hover opens only after a pause', async ({ visual: { page } }) => {
  const overlay = page.getByRole('form', { name: 'To-dos' }), inbox = page.getByRole('dialog', { name: 'GitHub inbox' });
  await expect(overlay).toHaveAttribute('data-open', 'false');
  const start = (await overlay.getByRole('button', { name: 'Keep to-dos open' }).boundingBox())!, end = (await page.getByRole('button', { name: 'Go to Undermap' }).boundingBox())!;
  await page.mouse.move(start.x + start.width / 2, start.y + 4);
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 8 });
  await page.waitForTimeout(400);
  await expect(overlay).toHaveAttribute('data-open', 'false'); await expect(inbox).toHaveCount(0);
  await page.mouse.move(1180, 710);
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'true');
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'false');
  await overlay.getByRole('button', { name: 'Keep to-dos open' }).hover();
  await expect(overlay).toHaveAttribute('data-open', 'true');
  await overlay.getByRole('button', { name: 'Keep to-dos open' }).click();
  await expect(page.locator('.tool-rail-slot[data-slot=todos]')).toHaveAttribute('data-pinned', 'true');
  await expect(overlay.getByRole('button', { name: 'Close to-dos' })).toHaveAttribute('aria-pressed', 'true');
  await page.mouse.move(1180, 710); await page.waitForTimeout(350);
  await expect(overlay).toHaveAttribute('data-open', 'true');
  await page.reload(); await expect(overlay).toHaveAttribute('data-open', 'false'); await expect(page.locator('.tool-rail-slot[data-slot=todos]')).not.toHaveAttribute('data-pinned');
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'true'); await expect(page.locator('.tool-rail-slot[data-slot=todos]')).toHaveAttribute('data-pinned', 'true');
  await expect(overlay.locator('.rail-panel-sheet')).toHaveScreenshot('todo-pinned.png');
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'false');
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'true');
  await overlay.getByRole('button', { name: 'Close to-dos' }).click();
  await expect(page.locator('.tool-rail-slot[data-slot=todos]')).not.toHaveAttribute('data-pinned'); await expect(overlay).toHaveAttribute('data-open', 'false');
  await page.waitForTimeout(400); await expect(overlay).toHaveAttribute('data-open', 'false');
  await page.mouse.move(1180, 710);
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'true');
  await page.mouse.move(1160, 700); await page.waitForTimeout(400); await expect(overlay).toHaveAttribute('data-open', 'true');
  await page.keyboard.press('t'); await expect(overlay).toHaveAttribute('data-open', 'false');
});

test('workspace shortcuts leave text editing, dialogs, menus and native terminals alone', async ({ visual: { page } }) => {
  const overlay = page.getByRole('form', { name: 'To-dos' });
  await page.keyboard.press('t');
  const draft = overlay.getByRole('textbox', { name: 'New to-do' });
  await draft.pressSequentially('test'); await expect(draft).toHaveValue('test');
  await expect(overlay).toHaveAttribute('data-open', 'true');
  await overlay.getByRole('button', { name: 'Close to-do list', exact: true }).click();
  await page.getByRole('button', { name: 'Settings', exact: true }).click();
  await page.getByRole('button', { name: 'Close settings' }).focus(); await page.keyboard.press('t');
  await expect(overlay).toHaveAttribute('data-open', 'false');
  await page.getByRole('button', { name: 'Close settings' }).click();
  await page.mouse.click(90, 80, { button: 'right' }); await page.keyboard.press('t');
  await expect(overlay).toHaveAttribute('data-open', 'false');
  await page.keyboard.press('Escape');
  await page.mouse.dblclick(450, 190); await page.keyboard.press('t');
  await expect(page.getByRole('form', { name: 'New item' })).toBeVisible();
  await expect(overlay).toHaveAttribute('data-open', 'false'); await page.keyboard.press('Escape');
  await openTerminal(page);
  await page.locator('.xterm-helper-textarea').focus(); await page.keyboard.press('t');
  await expect(overlay).toHaveAttribute('data-open', 'false');
  await expect(page.locator('.xterm-helper-textarea')).toBeFocused();
});

test('number keys drive the hotbar, letters open Needs me, Undermap and Settings, ? lists every key', async ({ visual: { page } }) => {
  const overlay = page.getByRole('form', { name: 'To-dos' }), inbox = page.locator('.github-inbox');
  await page.keyboard.press('2'); await expect(overlay).toHaveAttribute('data-open', 'true');
  await expect(page.locator('.tool-rail-slot[data-slot=todos]')).toHaveAttribute('data-pinned', 'true');
  await page.keyboard.press('2'); await expect(page.locator('.tool-rail-slot[data-slot=todos]')).not.toHaveAttribute('data-pinned');
  await page.mouse.move(1180, 710); await expect(overlay).toHaveAttribute('data-open', 'false');
  const reminders = page.locator('.reminders-tool');
  await page.keyboard.press('3'); await expect(reminders).toHaveAttribute('data-open', 'true');
  await page.keyboard.press('3'); await expect(reminders).toHaveAttribute('data-open', 'false');
  await page.keyboard.press('4'); await expect(inbox).toHaveAttribute('data-open', 'true');
  await page.keyboard.press('4'); await expect(inbox).toHaveAttribute('data-open', 'false');
  const needsMe = page.getByRole('dialog', { name: 'Needs me' });
  await page.keyboard.press('n'); await expect(needsMe).toBeVisible();
  await page.keyboard.press('n'); await expect(needsMe).toHaveCount(0);
  const zoom = () => page.locator('.map-area').getAttribute('data-zoom').then(Number);
  const start = await zoom();
  await page.keyboard.press('='); await expect.poll(zoom).toBeGreaterThan(start);
  await page.keyboard.press('0'); await expect.poll(zoom).toBeCloseTo(1, 2);
  await page.keyboard.press('-'); await expect.poll(zoom).toBeLessThan(1);
  await page.keyboard.press('Shift+?');
  const card = page.getByRole('dialog', { name: 'Controls' });
  await expect(card).toBeVisible();
  await expect(card.locator('section[aria-label="Hotbar"]')).toContainText('Reminders3'); await expect(card.locator('section[aria-label="Hotbar"]')).toContainText('GitHub inbox4');
  await expect(card).toHaveScreenshot('controls-card.png');
  await page.keyboard.press('Escape'); await expect(card).toHaveCount(0);
  await page.keyboard.press('u'); await expect(page.locator('.live-workspace')).toHaveAttribute('data-layer', 'below');
  await page.keyboard.press('5'); await expect(page.locator('.live-workspace')).toHaveAttribute('data-layer', 'map');
  await page.keyboard.press('6'); await expect(page.getByRole('menu', { name: 'Table actions' })).toHaveCount(STANDUP_ENABLED ? 1 : 0);
  await page.keyboard.press('Escape'); await expect(page.getByRole('menu', { name: 'Table actions' })).toHaveCount(0);
  await page.keyboard.press('7'); await expect(page.getByRole('dialog', { name: 'Settings' })).toBeVisible();
  await page.keyboard.press('Escape'); await expect(page.getByRole('dialog', { name: 'Settings' })).toHaveCount(0);
  await page.keyboard.press(','); await expect(page.getByRole('dialog', { name: 'Settings' })).toBeVisible();
  await page.keyboard.press('n'); await expect(needsMe).toHaveCount(0);
});

test('hotbar slots name themselves with their key on hover, and a pinned tool shows the selected plate', async ({ visual: { page } }) => {
  const tip = (slot: string) => page.locator(`.tool-rail-tip[data-slot=${slot}]`);
  await expect(tip('undermap')).toBeHidden();
  await page.getByRole('button', { name: 'Go to Undermap' }).hover();
  await expect(tip('undermap')).toBeVisible(); await expect(tip('undermap')).toHaveText('Undermap5 U');
  await expect(page.getByRole('button', { name: 'Go to Undermap' })).toHaveAttribute('aria-keyshortcuts', '5 U');
  await page.mouse.move(1180, 710); await expect(tip('undermap')).toBeHidden();
  await page.getByRole('button', { name: /^GitHub inbox/ }).focus();
  await expect(tip('inbox')).toBeVisible(); await expect(tip('inbox')).toContainText('GitHub inbox');
  await page.keyboard.press('Enter');
  await expect(page.locator('.tool-rail-slot[data-slot=inbox]')).toHaveAttribute('data-pinned', 'true');
  await expect(tip('inbox')).toBeHidden();
  await page.keyboard.press('Escape');
  await expect(page.locator('.tool-rail-slot[data-slot=inbox]')).not.toHaveAttribute('data-pinned');
  await page.keyboard.press('2'); await page.keyboard.press('Escape');
  await expect(page.getByRole('form', { name: 'To-dos' })).toHaveAttribute('data-open', 'false');
  await expect(page.locator('.tool-rail-slot[data-slot=todos]')).not.toHaveAttribute('data-pinned');
  await page.keyboard.press('2');
  await expect(page.locator('.tool-rail-slot[data-slot=todos]')).toHaveAttribute('data-pinned', 'true');
  await page.getByRole('button', { name: 'Go to Undermap' }).hover();
  await expect(tip('undermap')).toBeVisible();
  await expect(page).toHaveScreenshot('tool-rail-pinned-tip.png', { clip: { x: 0, y: 96, width: 200, height: 296 } });
});
