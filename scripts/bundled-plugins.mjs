/** Writes the bundled plugin entry lists from src/resource-plugins/bundled/plugins.json and
 * each package's act-plugin.json. `--check` fails instead of writing when they are stale. */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const bundled = join(root, 'src/resource-plugins/bundled');
const header = '// Generated by scripts/bundled-plugins.mjs from bundled/plugins.json and each act-plugin.json. Do not edit.\n';
const sdk = '../../../packages/plugin-sdk/host.ts';

const camel = folder => folder.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());

export function bundledPluginSources() {
  const folders = JSON.parse(readFileSync(join(bundled, 'plugins.json'), 'utf8'));
  const packages = folders.map(folder => ({ folder, name: camel(folder), manifest: JSON.parse(readFileSync(join(root, 'src/resource-plugins/items', folder, 'act-plugin.json'), 'utf8')) }));
  const path = (pkg, file) => `../items/${pkg.folder}/${file}`;
  const entry = (kind, type, exportName) => {
    const users = packages.filter(pkg => pkg.manifest.entries[kind]);
    return header + `import type { ${type} } from '${sdk}';\n`
      + users.map(pkg => `import ${pkg.name} from '${path(pkg, pkg.manifest.entries[kind])}';\n`).join('')
      + `\nexport const ${exportName}: Readonly<Record<string, ${type}>> = {\n`
      + users.map(pkg => `  '${pkg.manifest.id}': ${pkg.name},\n`).join('') + '};\n';
  };
  return {
    'packages.generated.ts': header + `import type { PluginDefinitionsModule } from '${sdk}';\n`
      + packages.map(pkg => `import ${pkg.name}Manifest from '${path(pkg, 'act-plugin.json')}' with { type: 'json' };\nimport ${pkg.name} from '${path(pkg, pkg.manifest.entries.definitions)}';\n`).join('')
      + `\nexport const bundledPackages: readonly { manifest: unknown; module: PluginDefinitionsModule }[] = [\n`
      + packages.map(pkg => `  { manifest: ${pkg.name}Manifest, module: ${pkg.name} },\n`).join('') + '];\n',
    'service.generated.ts': entry('service', 'ServiceModule', 'bundledServiceModules'),
    'renderer.generated.ts': entry('renderer', 'RendererModule', 'bundledRendererModules'),
    'styles.generated.css': `/* ${header.slice(3).trim()} */\n` + packages.flatMap(pkg => (pkg.manifest.contributes?.css ?? []).map(file => `@import '${path(pkg, file)}';\n`)).join(''),
  };
}

export function staleBundledPluginFiles() {
  return Object.entries(bundledPluginSources()).filter(([file, source]) => {
    try { return readFileSync(join(bundled, file), 'utf8') !== source; } catch { return true; }
  }).map(([file]) => file);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const stale = staleBundledPluginFiles();
    if (stale.length) { console.error(`Stale bundled plugin files: ${stale.join(', ')}. Run node scripts/bundled-plugins.mjs.`); process.exitCode = 1; }
  } else {
    for (const [file, source] of Object.entries(bundledPluginSources())) writeFileSync(join(bundled, file), source);
    console.log('Wrote bundled plugin entry lists.');
  }
}
