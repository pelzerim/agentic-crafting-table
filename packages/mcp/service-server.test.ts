import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
import { startWorkspaceService } from '../workspace-service/server.ts';
import { connectWorkspace } from '../workspace-service/client.ts';

test('production stdio MCP shares the service state, identities and replay rules', async () => {
  const directory = await mkdtemp(join(tmpdir(), 'craft-service-mcp-'));
  const service = await startWorkspaceService(directory, undefined, undefined, { assignments: [] }), observer = await connectWorkspace(directory);
  const client = new Client({ name: 'service-agent', version: '1' });
  try {
    await client.connect(new StdioClientTransport({ command: process.execPath, args: [resolve('packages/mcp/entry.ts')], env: { ACT_DATA_DIR: directory, ACT_PROJECT_ID: 'project', ACT_NODE_ID: 'agent' }, stderr: 'pipe' }));
    assert.match(client.getInstructions()!, /"agentNodeId":"agent"/);
    const command = { commandId: 'create-project', expectedRevision: 0, command: { type: 'project.create', id: 'project', title: 'Connected via MCP', position: { x: 20, y: 30 } } };
    const parse = (result: any) => JSON.parse(result.content[0].text);
    const settings = parse(await client.callTool({ name: 'workspace_settings', arguments: {} }));
    assert.equal(settings.value.claude.remoteControl, true);
    assert.equal(settings.value.claude.autoMode, true);
    const providers = parse(await client.callTool({ name: 'workspace_connections', arguments: {} }));
    assert.equal(providers.providers[0].id, 'github'); assert.deepEqual(providers.connections, []);
    const connections = [{ id: 'github-fixture', providerId: 'github', account: 'fixture', enabled: true, isDefault: true }];
    const changed = parse(await client.callTool({ name: 'workspace_settings', arguments: { update: { expectedRevision: settings.revision, value: { ...settings.value, claude: { ...settings.value.claude, autoMode: false }, connections, keepAwake: true, neighborhoodPadding: 360, neighborhoodAppearance: { pixelSize: 32, fade: 120, scatter: 45, style: 'plain', texture: 'medium' }, quickItemTypes: ['workspace.todo', 'project'] } } } }));
    assert.deepEqual(parse(await client.callTool({ name: 'workspace_connections', arguments: {} })).connections, connections);
    assert.deepEqual(parse(await client.callTool({ name: 'workspace_sync_connections', arguments: {} })), []);
    assert.equal((await observer.call<any>('settings.read')).revision, changed.revision);
    assert.equal((await observer.call<any>('settings.read')).value.claude.autoMode, false);
    assert.equal((await observer.call<any>('settings.read')).value.keepAwake, true);
    assert.equal((await observer.call<any>('settings.read')).value.neighborhoodPadding, 360);
    assert.deepEqual((await observer.call<any>('settings.read')).value.neighborhoodAppearance, { pixelSize: 32, fade: 120, scatter: 45, style: 'plain', texture: 'medium', brightness: 24 });
    assert.deepEqual((await observer.call<any>('settings.read')).value.quickItemTypes, ['workspace.todo', 'project']);
    const invalidSettings = await client.callTool({ name: 'workspace_settings', arguments: { update: { expectedRevision: changed.revision, value: { ...changed.value, neighborhoodPadding: -1 } } } });
    assert.equal(invalidSettings.isError, true);
    const invalidAppearance = await client.callTool({ name: 'workspace_settings', arguments: { update: { expectedRevision: changed.revision, value: { ...changed.value, neighborhoodAppearance: { pixelSize: 0, fade: 96, scatter: 0 } } } } });
    assert.equal(invalidAppearance.isError, true);
    const invalidStyle = await client.callTool({ name: 'workspace_settings', arguments: { update: { expectedRevision: changed.revision, value: { ...changed.value, neighborhoodAppearance: { ...changed.value.neighborhoodAppearance, style: 'fancy' } } } } });
    assert.equal(invalidStyle.isError, true);
    assert.equal((await observer.call<any>('settings.read')).revision, changed.revision);
    const staleSettings = await client.callTool({ name: 'workspace_settings', arguments: { update: { expectedRevision: 0, value: settings.value } } });
    assert.equal(parse(staleSettings).error.code, 'REVISION_CONFLICT');
    const first = parse(await client.callTool({ name: 'workspace_apply', arguments: command }));
    assert.equal(first.revision, 1);
    assert.equal(parse(await client.callTool({ name: 'workspace_apply', arguments: command })).replayed, true);
    assert.equal((await observer.call<any>('read')).state.nodes[0].title, 'Connected via MCP');
    const diagnostic = parse(await client.callTool({ name: 'workspace_diagnostics', arguments: {} }));
    assert.equal(diagnostic.workspace.projects, 1); assert.ok(!JSON.stringify(diagnostic).includes('Connected via MCP'));
    const discovery = parse(await client.callTool({ name: 'workspace_plugins', arguments: { input: 'https://github.com/example/project/pull/42' } }));
    assert.deepEqual(discovery.urlCandidates.map((candidate: any) => candidate.pluginId), ['github.pull-request']);
    assert.equal(discovery.candidates[0].pluginId, 'github.pull-request');
    assert.ok(discovery.plugins.some((plugin: any) => plugin.id === 'workspace.todo' && plugin.capabilities.context));
    const rejected = await client.callTool({ name: 'workspace_apply', arguments: { expectedRevision: 0, command: { type: 'node.archive', id: 'project' } } });
    assert.equal(rejected.isError, true); assert.equal(parse(rejected).error.code, 'REVISION_CONFLICT');
    const invalid = await client.callTool({ name: 'workspace_run', arguments: { action: 'agent.start', nodeId: 'project', arguments: { systemPrompt: 'replace the host' } } });
    assert.equal(invalid.isError, true);
    const guide = await client.readResource({ uri: 'benchgrove://agent-guide' });
    assert.ok('text' in guide.contents[0]);
    assert.match(String(guide.contents[0].text), /Keep the map in sync/);
    assert.ok(!String(guide.contents[0].text).includes('replace the host'));
    assert.equal((await service.store.read()).revision, 1);
  } finally { await client.close(); observer.close(); await service.close(); await rm(directory, { recursive: true, force: true }); }
});
